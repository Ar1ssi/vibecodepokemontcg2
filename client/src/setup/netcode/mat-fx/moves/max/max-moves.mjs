// Design 092: the Sword/Shield Max Moves and G-Max Moves a Pokémon VMAX's Dynamax attack plays.
// A "Max …" attack plays the Max Move of the Pokémon's own game type (one per type, 18); a
// "G-Max …" attack plays its species' G-Max Move (33, one per Gigantamax Pokémon). TCG G-Max
// attacks are named for the card, not the game ("G-Max Swallow Up" is Gengar's G-Max Terror), so
// G-Max Moves key on species. Names and types: Bulbapedia's G-Max Move table and PokéAPI
// (max-* moves); reference clips: Poképédia `<Nom>_EB.mp4`.

