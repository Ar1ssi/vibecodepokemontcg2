// Regenerates client/src/setup/deck-builder/core/gen-1-2-order.generated.mjs: every card of
// Base Set, Fossil, Base Set 2 and Neo Genesis. Pokémon by National Pokédex number, then
// Trainers, then Energy. Ties break by set (release order), then card number. Reprints are dropped, keeping the
// oldest printing: Pokémon match on name + HP + type (same-HP reprints, even with reworded attacks), Trainers
// and Energy on name.
import fs from 'node:fs';

const SETS = ['base1', 'base3', 'base4', 'neo1'];
const BASE = 'https://api.tcgdex.net/v2/en';
const CATEGORY_RANK = { Pokemon: 0, Trainer: 1, Energy: 2 };

const get = async (path) => {
  const res = await fetch(`${BASE}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
};

const reprintKey = (detail) =>
  detail.category === 'Pokemon'
    ? JSON.stringify([detail.name, detail.hp, detail.types])
    : detail.name;

const rows = [];
for (const [setRank, setId] of SETS.entries()) {
  const record = await get(`sets/${setId}`);
  const cards = record.cards.filter((card) => card.image);
  let next = 0;
  const worker = async () => {
    while (next < cards.length) {
      const card = cards[next++];
      const detail = await get(`cards/${card.id}`);
      rows.push({
        id: card.id,
        name: card.name,
        setRank,
        number: parseInt(card.localId, 10),
        categoryRank: CATEGORY_RANK[detail.category] ?? 3,
        dex: detail.dexId?.[0] ?? Infinity,
        reprintKey: reprintKey(detail),
      });
    }
  };
  await Promise.all(Array.from({ length: 12 }, worker));
}

rows.sort((a, b) => a.categoryRank - b.categoryRank || a.dex - b.dex || a.setRank - b.setRank || a.number - b.number);

const seen = new Set();
const unique = rows.filter((row) => {
  if (seen.has(row.reprintKey)) return false;
  seen.add(row.reprintKey);
  return true;
});

const noDex = rows.filter((row) => row.categoryRank === 0 && row.dex === Infinity).map((row) => row.id);
if (noDex.length) console.warn(`Pokémon without a dex number (sorted last among Pokémon): ${noDex.join(', ')}`);

const target = new URL('../client/src/setup/deck-builder/core/gen-1-2-order.generated.mjs', import.meta.url);
const body = unique.map((row) => `  '${row.id}',`).join('\n');
fs.writeFileSync(target, `// Generated by scripts/generate-gen12-order.mjs — do not edit.\nexport const GEN_1_2_ORDER = [\n${body}\n];\n`);
console.log(`${unique.length} cards (${rows.length - unique.length} reprints dropped)`);
