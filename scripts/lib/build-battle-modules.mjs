/**
 * Row shapes and module text for the baked Build & Battle data (design 054 § Generated data):
 * `sets/<setId>.generated.mjs` (compact rows, art URLs derived at load) and
 * `boxes/<boxKey>.generated.mjs` (the box's own cards in full, referenced by id).
 */

const HEADER = '// AUTO-GENERATED by scripts/generate-build-battle-box.mjs — do not edit by hand.';

const supertypeOf = (category) =>
  category === 'Pokemon' ? 'Pokémon' : category === 'Energy' ? 'Energy' : 'Trainer';

/** The pack-opening fields of a card row; `card` null = a baked Basic Energy (051). */
export function setCardFields(card) {
  if (!card) return { rarity: null, category: 'Energy', stage: null, types: [], hp: null };
  return {
    rarity: card.rarity || null,
    category: card.category,
    stage: card.stage || null,
    types: Array.isArray(card.types) ? card.types : [],
    hp: Number.isFinite(card.hp) ? card.hp : null,
  };
}

/**
 * A set module row: what pack opening and the pool need, without art or set (both derived at
 * load). `images` is kept only when TCGdex has no art for the card (design 054 D4).
 */
export function toSetRow(card, { subset = null, images = null } = {}) {
  if (!card.rarity) throw new Error(`${card.id} has no rarity on TCGdex`);
  return {
    id: card.id,
    name: card.name,
    supertype: supertypeOf(card.category),
    localId: String(card.localId ?? ''),
    ...setCardFields(card),
    ...(subset ? { subset } : {}),
    ...(images ? { images } : {}),
  };
}

function serialize(value, indent = '') {
  const inner = `${indent}  `;
  if (Array.isArray(value)) {
    const isRowList = value.length > 0 && value.every((item) => item?.id && item?.name);
    if (!isRowList) return JSON.stringify(value);
    return `[\n${value.map((item) => `${inner}${JSON.stringify(item)}`).join(',\n')}\n${indent}]`;
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).map(
      ([key, item]) => `${inner}${JSON.stringify(key)}: ${serialize(item, inner)}`
    );
    return `{\n${entries.join(',\n')}\n${indent}}`;
  }
  return JSON.stringify(value);
}

/** @returns {string} `sets/<setId>.generated.mjs`: `export const SET` and `export default` rows. */
export function renderSetModule(set, rows) {
  return [
    HEADER,
    `// ${set.name} (${set.id}): ${rows.length} cards from TCGdex, sorted by localId.`,
    `export const SET = ${JSON.stringify(set)};`,
    '',
    `export default ${serialize(rows)};`,
    '',
  ].join('\n');
}

/** @returns {string} `boxes/<boxKey>.generated.mjs`: the box data as one default export. */
export function renderBoxModule({ name, source }, data) {
  return [
    HEADER,
    `// ${name}: ${source.url} (Bulbapedia revision ${source.revision}).`,
    `export default ${serialize(data)};`,
    '',
  ].join('\n');
}
