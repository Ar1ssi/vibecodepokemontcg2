// Regenerates client/src/setup/deck-builder/core/black-bolt-white-flare-order.generated.mjs.
// Order: regular Pokémon by Unova (Gen 5, National #494-649) Pokédex number, regular Trainers,
// Energy, then the art rares (illustration, special illustration, ultra, black/white rare):
// Pokémon by dex, then Trainers. Ties break by set (Black Bolt first), then number.
import fs from 'node:fs';

const SETS = ['sv10.5b', 'sv10.5w'];
const BASE = 'https://api.tcgdex.net/v2/en';
const CATEGORY_RANK = { Pokemon: 0, Trainer: 1, Energy: 2 };
const ART_RARE_RANK = 3; // group offset: art rares trail every regular card
const ART_RARITIES = new Set(['Illustration rare', 'Special illustration rare', 'Ultra Rare', 'Black White Rare']);

const get = async (path) => {
  const res = await fetch(`${BASE}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
};

const rows = [];
for (const [setRank, setId] of SETS.entries()) {
  const record = await get(`sets/${setId}`);
  const cards = record.cards.filter((card) => card.image);
  let next = 0;
  const worker = async () => {
    while (next < cards.length) {
      const card = cards[next++];
      const detail = await get(`cards/${card.id}`);
      rows.push({
        id: card.id,
        setRank,
        number: parseInt(card.localId, 10),
        categoryRank: (CATEGORY_RANK[detail.category] ?? 2) + (ART_RARITIES.has(detail.rarity) ? ART_RARE_RANK : 0),
        dex: detail.dexId?.[0] ?? Infinity,
      });
    }
  };
  await Promise.all(Array.from({ length: 12 }, worker));
}

rows.sort((a, b) => a.categoryRank - b.categoryRank || a.dex - b.dex || a.setRank - b.setRank || a.number - b.number);

const target = new URL('../client/src/setup/deck-builder/core/black-bolt-white-flare-order.generated.mjs', import.meta.url);
const body = rows.map((row) => `  '${row.id}',`).join('\n');
fs.writeFileSync(target, `// Generated by scripts/generate-bbwf-order.mjs — do not edit.\nexport const BLACK_BOLT_WHITE_FLARE_ORDER = [\n${body}\n];\n`);
console.log(`${rows.length} cards -> ${target.pathname}`);
