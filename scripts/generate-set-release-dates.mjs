// Regenerates client/src/setup/deck-builder/core/set-release-dates.generated.mjs: every TCGdex set's
// release date, keyed by set id. Search ranks cards by printing date with this table, because TCGdex
// answers card searches in collector-number order and cannot sort by date. Sets without a well-formed
// date are left out (and listed on stderr); card-search.mjs then falls back to fetching such a set.
// Run: node scripts/generate-set-release-dates.mjs           (rewrite the module)
//      node scripts/generate-set-release-dates.mjs --check   (re-fetch; exit 1 when the module would change)
import fs from 'node:fs';

const BASE = 'https://api.tcgdex.net/v2/en';
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
const CHECK = process.argv.includes('--check');

const get = async (path) => {
  const res = await fetch(`${BASE}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
};

const sets = await get('sets');
const records = [];
let next = 0;
const worker = async () => {
  while (next < sets.length) {
    const set = sets[next++];
    const record = await get(`sets/${set.id}`);
    records.push({ id: set.id, releaseDate: record.releaseDate });
  }
};
await Promise.all(Array.from({ length: 8 }, worker));

const dated = records.filter((record) => DATE_PATTERN.test(record.releaseDate || ''));
const undated = records.filter((record) => !DATE_PATTERN.test(record.releaseDate || ''));
if (undated.length) {
  console.warn(`Sets without a release date (left out): ${undated.map((record) => record.id).sort().join(', ')}`);
}

dated.sort((a, b) => a.id.localeCompare(b.id));
const body = dated.map((record) => `  '${record.id}': '${record.releaseDate}',`).join('\n');
const text = `// Generated by scripts/generate-set-release-dates.mjs — do not edit.
// TCGdex set id -> release date, so search can rank cards by printing date (card-search.mjs).
export const SET_RELEASE_DATES = {
${body}
};
`;

const target = new URL('../client/src/setup/deck-builder/core/set-release-dates.generated.mjs', import.meta.url);

if (!CHECK) {
  fs.writeFileSync(target, text);
  console.log(`${dated.length} sets written`);
} else {
  const onDisk = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (onDisk === text) {
    console.log(`set-release-dates.generated.mjs is up to date (${dated.length} sets)`);
  } else {
    const parse = (source) =>
      new Map([...source.matchAll(/^ {2}'([^']+)': '([^']+)',$/gm)].map((match) => [match[1], match[2]]));
    const before = parse(onDisk);
    const after = parse(text);
    const added = [...after.keys()].filter((id) => !before.has(id));
    const removed = [...before.keys()].filter((id) => !after.has(id));
    const changed = [...after.keys()].filter((id) => before.has(id) && before.get(id) !== after.get(id));
    console.error(
      `set-release-dates.generated.mjs is stale. added: [${added.join(', ')}] changed: [${changed.join(', ')}] removed: [${removed.join(', ')}]`
    );
    process.exitCode = 1;
  }
}
