/**
 * Bakes shared/engine/rules/paradox-tags.generated.mjs (design 058): every printing that carries
 * the Ancient or Future tag, keyed by TCGdex card id. TCGdex has no field for the tag, so the list
 * comes from pokemontcg.io `subtypes`; each id is then fetched on TCGdex and must name the same card.
 * Run: node scripts/generate-paradox-tags.mjs            (rewrite the module)
 *      node scripts/generate-paradox-tags.mjs --check    (re-fetch; exit 1 when the module would change)
 * TCGDEX_CACHE_DIR=<dir> keeps TCGdex responses between runs (development only).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fetchCard } from './lib/decklist-lines.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '../shared/engine/rules/paradox-tags.generated.mjs');
const PTCGIO_CARDS = 'https://api.pokemontcg.io/v2/cards';
const TAGS = ['Ancient', 'Future'];
const PAGE_SIZE = 250;
const RETRIES = 3;

// pokemontcg.io "sv4" / "sv4pt5" / "svp" → TCGdex "sv04" / "sv04.5" / "svp".
export function tcgdexSetId(ptcgioSetId) {
  const set = String(ptcgioSetId || '').toLowerCase();
  const sv = set.match(/^sv(\d+)(pt5)?$/);
  if (sv) return `sv${sv[1].padStart(2, '0')}${sv[2] ? '.5' : ''}`;
  if (set === 'svp') return 'svp';
  return null;
}

export function tcgdexCardId(ptcgioCard) {
  const setId = tcgdexSetId(ptcgioCard?.set?.id);
  const number = String(ptcgioCard?.number || '').trim();
  if (!setId || !/^\d+$/.test(number)) return null;
  return `${setId}-${number.padStart(3, '0')}`;
}

const sameName = (a, b) => {
  const norm = (s) => String(s || '').replace(/[’‘`]/g, "'").trim().toLowerCase();
  return norm(a) === norm(b);
};

async function fetchJson(url) {
  for (let attempt = 0; ; attempt += 1) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`pokemontcg.io fetch failed (${res.status}) for ${url}`);
      return await res.json();
    } catch (err) {
      if (attempt >= RETRIES) throw err;
      await new Promise((resolve) => setTimeout(resolve, 1000 * 2 ** attempt));
    }
  }
}

async function taggedPrintings(tag) {
  const cards = [];
  for (let page = 1; ; page += 1) {
    const url =
      `${PTCGIO_CARDS}?q=subtypes:${tag.toLowerCase()}` +
      `&select=id,name,number,set,subtypes&pageSize=${PAGE_SIZE}&page=${page}`;
    const json = await fetchJson(url);
    const data = Array.isArray(json?.data) ? json.data : [];
    cards.push(...data);
    if (data.length < PAGE_SIZE) break;
  }
  if (cards.length === 0) throw new Error(`pokemontcg.io returned no ${tag} cards`);
  return cards;
}

export async function collectParadoxTags({ fetchPrintings = taggedPrintings, fetchTcgdexCard = fetchCard } = {}) {
  const tags = {};
  for (const tag of TAGS) {
    for (const card of await fetchPrintings(tag)) {
      const id = tcgdexCardId(card);
      if (!id) throw new Error(`No TCGdex id for pokemontcg.io ${card.id} (${card.name})`);
      if (tags[id] && tags[id] !== tag) throw new Error(`${id} is tagged both ${tags[id]} and ${tag}`);
      const tcgdex = await fetchTcgdexCard(id);
      if (!sameName(tcgdex?.name, card.name)) {
        throw new Error(`${id} is "${tcgdex?.name}" on TCGdex, pokemontcg.io ${card.id} is "${card.name}"`);
      }
      tags[id] = tag;
    }
  }
  return tags;
}

export function renderParadoxTagsModule(tags) {
  const lines = Object.keys(tags)
    .sort()
    .map((id) => `  '${id}': '${tags[id]}',`);
  return [
    '// Generated by scripts/generate-paradox-tags.mjs (design 058) — do not edit by hand.',
    '// Printings that carry the Ancient or Future tag, keyed by TCGdex card id. Source:',
    '// pokemontcg.io `subtypes` (TCGdex has no tag field), each id name-checked on TCGdex.',
    'export const PARADOX_TAGS = Object.freeze({',
    ...lines,
    '});',
    '',
  ].join('\n');
}

async function main() {
  const check = process.argv.includes('--check');
  const tags = await collectParadoxTags();
  const next = renderParadoxTagsModule(tags);
  if (check) {
    const current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (current !== next) {
      console.error('paradox-tags.generated.mjs is out of date: run node scripts/generate-paradox-tags.mjs');
      process.exitCode = 1;
      return;
    }
    console.log('paradox-tags.generated.mjs is up to date');
    return;
  }
  writeFileSync(OUT, next);
  console.log(`wrote ${Object.keys(tags).length} tagged printings to ${OUT}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((err) => {
    console.error(err.message);
    process.exitCode = 1;
  });
}
